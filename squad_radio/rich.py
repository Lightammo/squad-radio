"""Rich KMarkdown formatting for KOOK broadcasts.

KOOK KMarkdown supports bold/italic/underline/strikethrough, quotes, inline
code, dividers, emoji shortcodes, mentions ``(met)id(met)``, spoilers
``(spl)..(spl)`` and link thumbnails. It does NOT support ``![alt](url)``.

So images are embedded as link thumbnails: a markdown link whose label equals
its URL renders as a preview. The image files are hosted on KOOK's own CDN
(img.kookapp.cn) to avoid hotlink protection.
"""
from __future__ import annotations

from dataclasses import dataclass
from typing import Any

from .models import Broadcast

# Permanent KOOK CDN URLs (public asset links, not secrets). Generated by
# scripts/generate_assets.py and uploaded via KookClient.upload_asset().
DEFAULT_IMAGES: dict[str, str] = {
    "password": "https://img.kookapp.cn/attachments/2026-11/18/2BTP1jDuho0og09g.png",
    "red": "https://img.kookapp.cn/attachments/2026-11/18/TJMQc0Q9EH0og09g.png",
    "market": "https://img.kookapp.cn/attachments/2026-11/18/VtJrwri3kI0og09g.png",
    "task": "https://img.kookapp.cn/attachments/2026-11/18/lTj96tMSna0og09g.png",
}

_KIND_META: dict[str, tuple[str, str]] = {
    "price": ("market", "📈 行情异动播报"),
    "red": ("red", "💎 高价值物资"),
    "password": ("password", "🔑 今日作战密码"),
    "task": ("task", "🔧 特勤处完工"),
}

_SPLASHES: dict[str, str] = {
    "price": "(spl)先别急着all in，看看群里怎么说(spl)",
    "red": "(spl)群里先安静三秒，恭喜就完事了(spl)",
    "password": "(spl)记不住没关系，随时在群里喊「今日密码」(spl)",
    "task": "(spl)产能这种东西，放着是会过期的哦(spl)",
}


def thumb(url: str | None) -> str:
    """Return a KOOK link-thumbnail snippet, or empty when no URL."""
    if not url:
        return ""
    return f"[{url}]({url})"


def _kind_of(event_key: str) -> str:
    head = event_key.split(":", 1)[0]
    return head if head in _KIND_META else "info"


def _as_mention(text: str, user_id: str | None) -> str:
    """Convert plain '@123' style mentions into KOOK (met) syntax."""
    if not user_id:
        return text
    return text.replace(f"@{user_id}", f"(met){user_id}(met)")


@dataclass
class RichStyle:
    """Toggles for how decorative the formatting should be."""

    images: dict[str, str] | None = None
    show_thumbnail: bool = True
    show_splash: bool = True
    show_actions: bool = True

    def image(self, kind: str) -> str | None:
        store = self.images if self.images is not None else DEFAULT_IMAGES
        return store.get(kind)


def format_broadcast(broadcast: Broadcast, style: RichStyle | None = None) -> str:
    """Render a Broadcast as a decorated KMarkdown card.

    The broadcast text is already persona-voiced by the engine, so this layer
    only adds structure: a thumbnail, a titled header, the body, a spoiler
    easter-egg and the quick-action hint.
    """
    style = style or RichStyle()
    kind = _kind_of(broadcast.event_key)
    theme, title = _KIND_META.get(kind, ("password", "📻 战地播报"))

    lines: list[str] = []
    if style.show_thumbnail:
        snippet = thumb(style.image(theme))
        if snippet:
            lines.append(snippet)

    lines.append(f"**{title}**")
    lines.append(_as_mention(broadcast.text.strip(), broadcast.target_user_id))

    if style.show_splash and kind in _SPLASHES:
        lines.append(_SPLASHES[kind])

    parts = [line for line in lines if line]
    if style.show_actions and broadcast.actions:
        actions = " ｜ ".join(f"`{item}`" for item in broadcast.actions)
        parts.append("---")
        parts.append(f"快捷指令：{actions}")
    return "\n".join(parts)


def format_password_card(
    lines: list[str],
    *,
    title: str,
    mention: str | None = None,
    footnote: str = "数据每天早上更新，以游戏内为准哦。",
    style: RichStyle | None = None,
) -> str:
    """Build the always-on '今日密码' reply card (KMarkdown)."""
    style = style or RichStyle()
    out: list[str] = []
    if style.show_thumbnail:
        snippet = thumb(style.image("password"))
        if snippet:
            out.append(snippet)

    header = f"**{title}**"
    if mention:
        header = f"{mention} {header}"
    out.append(header)
    out.extend(lines)
    if style.show_splash:
        out.append(_SPLASHES["password"])
    out.append("---")
    out.append(f"> {footnote}")
    return "\n".join(out)
